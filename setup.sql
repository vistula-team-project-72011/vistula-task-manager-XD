-- Run this once in Supabase SQL Editor

create table tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  completed boolean default false
);

alter table tasks enable row level security;

create policy "public select" on tasks for select to anon using (true);
create policy "public insert" on tasks for insert to anon with check (true);
create policy "public update" on tasks for update to anon using (true) with check (true);
create policy "public delete" on tasks for delete to anon using (true);

grant select, insert, update, delete on tasks to anon;
